# Deities depicted with animal heads (Anubis, Ganesha, Horus, ...) are not counted:
# they are gods, not creatures. Hanuman and Sun Wukong are counted because they are
# literally monkeys in their source texts.


def _plural(word: str) -> str:
    if word.endswith(("s", "x", "z", "ch", "sh")):
        return word + "es"
    if word.endswith("y") and word[-2:-1] not in "aeiou":
        return word[:-1] + "ies"
    return word + "s"


def forms(term: str) -> list[str]:
    """'monkey' -> ['monkey', 'monkeys']; 'ox|oxen' -> ['ox', 'oxen'];
    'Hanuman|' (empty plural) -> ['Hanuman']."""
    if "|" in term:
        sing, plur = term.split("|", 1)
        return [sing] + ([plur] if plur and plur != sing else [])
    if " " in term:  # multi-word: pluralise the last word
        head, last = term.rsplit(" ", 1)
        return [term, f"{head} {_plural(last)}"]
    return [term, _plural(term)]


def entries() -> list[dict]:
    """Flattened lexicon: one row per surface form."""
    out = []
    for group, terms in GROUPS.items():
        for term, flags in terms:
            base = term.split("|")[0]
            for f in forms(term):
                out.append({
                    "form": f, "lemma": base, "group": group,
                    "mythical": "m" in flags, "noun_only": "n" in flags,
                    "lower_only": "l" in flags,
                })
    return out
